import type { Metadata } from 'next';

export const SITE_URL = 'https://www.b2transport.in';
export const SITE_NAME = 'B2 Transport';
export const BUSINESS_ID = `${SITE_URL}/#business`;

// Bump when page content changes; used for sitemap <lastmod>.
export const CONTENT_LAST_UPDATED = '2026-10-26';

// Build a tel: href with country code. Stored numbers may or may not include it.
export function telHref(phone: string): string {
  const digits = phone.replace(/[^\d+]/g, '');
  if (digits.startsWith('+')) return `tel:${digits}`;
  if (digits.startsWith('91') && digits.length === 12) return `tel:+${digits}`;
  return `tel:+91${digits}`;
}

interface PageSeo {
  title: string;
  description: string;
  path: string;
}

// Generated by src/app/opengraph-image.tsx. Pages that set their own openGraph
// object replace the inherited one, so the image has to be listed again here.
const DEFAULT_SHARE_IMAGE = {
  url: '/opengraph-image',
  width: 1200,
  height: 630,
  alt: 'B2 Transport - Packers and Movers and Goods Transport in Ranchi, Jharkhand',
};

// Page-level metadata. Each page sets its own canonical, Open Graph and Twitter
// fields so nothing is inherited from the homepage.
export function pageMetadata({ title, description, path }: PageSeo): Metadata {
  return {
    title: { absolute: title },
    description,
    alternates: { canonical: path },
    openGraph: {
      title,
      description,
      url: path,
      siteName: SITE_NAME,
      locale: 'en_IN',
      type: 'website',
      images: [DEFAULT_SHARE_IMAGE],
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      images: [DEFAULT_SHARE_IMAGE.url],
    },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        'max-image-preview': 'large',
        'max-snippet': -1,
        'max-video-preview': -1,
      },
    },
  };
}
